//go:build ignore

// gen_tables writes tables.go from the Unicode Character Database: every
// Default_Ignorable_Code_Point (DerivedCoreProperties.txt), the UTS #39
// confusables mapping (confusables.txt) and the UTS #39 Allowed identifier
// characters (IdentifierStatus.txt). The version and the files' SHA-256
// are pinned here; run `go generate ./internal/safe` after changing them.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
)

const version = "17.0.0"

var sources = []struct{ url, sha256 string }{
	{"https://www.unicode.org/Public/" + version + "/ucd/DerivedCoreProperties.txt",
		"24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"},
	{"https://www.unicode.org/Public/" + version + "/security/confusables.txt",
		"091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a"},
	{"https://www.unicode.org/Public/" + version + "/security/IdentifierStatus.txt",
		"617228a16da13850bf8af28b6cd08f5e9b6595d2eb60404fe6eee2c85b4e4a35"},
}

func fetch(url, want string) []byte {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	if sum := sha256.Sum256(b); hex.EncodeToString(sum[:]) != want {
		log.Fatalf("%s: sha256 %x, want %s", url, sum, want)
	}
	return b
}

func cp(s string) rune {
	n, err := strconv.ParseUint(strings.TrimSpace(s), 16, 32)
	if err != nil {
		log.Fatalf("bad code point %q", s)
	}
	return rune(n)
}

// lines yields the data fields of a UCD file, comments stripped.
func lines(b []byte, f func(fields []string)) {
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		l, _, _ := strings.Cut(sc.Text(), "#")
		if strings.TrimSpace(l) == "" {
			continue
		}
		fields := strings.Split(l, ";")
		for i := range fields {
			fields[i] = strings.TrimSpace(fields[i])
		}
		f(fields)
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
}

type span struct{ lo, hi rune }

// spans collects the ranges whose second field is prop, merging neighbours.
func spans(b []byte, prop string) []span {
	var out []span
	lines(b, func(f []string) {
		if len(f) < 2 || f[1] != prop {
			return
		}
		lo, hi, ok := strings.Cut(f[0], "..")
		if !ok {
			hi = lo
		}
		out = append(out, span{cp(lo), cp(hi)})
	})
	slices.SortFunc(out, func(a, b span) int { return int(a.lo - b.lo) })
	var merged []span
	for _, s := range out {
		if n := len(merged); n > 0 && s.lo <= merged[n-1].hi+1 {
			merged[n-1].hi = max(merged[n-1].hi, s.hi)
			continue
		}
		merged = append(merged, s)
	}
	return merged
}

func table(b *bytes.Buffer, name, doc string, ss []span) {
	fmt.Fprintf(b, "// %s\nvar %s = &unicode.RangeTable{\n\tR16: []unicode.Range16{\n", doc, name)
	for _, s := range ss {
		if s.lo <= 0xffff {
			fmt.Fprintf(b, "\t\t{Lo: 0x%04x, Hi: 0x%04x, Stride: 1},\n", s.lo, min(s.hi, 0xffff))
		}
	}
	fmt.Fprintf(b, "\t},\n\tR32: []unicode.Range32{\n")
	for _, s := range ss {
		if s.lo > 0xffff {
			fmt.Fprintf(b, "\t\t{Lo: 0x%x, Hi: 0x%x, Stride: 1},\n", s.lo, s.hi)
		} else if s.hi > 0xffff {
			fmt.Fprintf(b, "\t\t{Lo: 0x10000, Hi: 0x%x, Stride: 1},\n", s.hi)
		}
	}
	fmt.Fprintf(b, "\t},\n}\n\n")
}

func main() {
	ign := spans(fetch(sources[0].url, sources[0].sha256), "Default_Ignorable_Code_Point")
	allowed := spans(fetch(sources[2].url, sources[2].sha256), "Allowed")

	conf := map[rune][]rune{}
	lines(fetch(sources[1].url, sources[1].sha256), func(f []string) {
		if len(f) < 2 {
			return
		}
		var to []rune
		for _, c := range strings.Fields(f[1]) {
			to = append(to, cp(c))
		}
		conf[cp(f[0])] = to
	})
	keys := make([]rune, 0, len(conf))
	for k := range conf {
		keys = append(keys, k)
	}
	slices.Sort(keys)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_tables.go from Unicode %s data; DO NOT EDIT.\n", version)
	fmt.Fprintf(&b, "// Unicode data © Unicode, Inc., under the Unicode License v3 (LICENSE-UNICODE).\n\n")
	fmt.Fprintf(&b, "package safe\n\nimport \"unicode\"\n\n")
	fmt.Fprintf(&b, "// UnicodeVersion is the version of the data below.\nconst UnicodeVersion = %q\n\n", version)
	table(&b, "defaultIgnorable", "defaultIgnorable is every Default_Ignorable_Code_Point, assigned or not.", ign)
	table(&b, "allowed", "allowed is the UTS #39 Identifier_Status=Allowed set.", allowed)
	fmt.Fprintf(&b, "// confusables maps a code point to its UTS #39 prototype.\nvar confusables = map[rune]string{\n")
	for _, k := range keys {
		var q strings.Builder
		for _, c := range conf[k] {
			fmt.Fprintf(&q, "\\U%08x", c)
		}
		fmt.Fprintf(&b, "\t0x%x: \"%s\",\n", k, q.String())
	}
	fmt.Fprintf(&b, "}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("tables.go: %d ignorable ranges, %d allowed ranges, %d confusables (Unicode %s)\n", len(ign), len(allowed), len(keys), version)
}
